// Copies the rule methods of the upstream C# into golden/upstream/Extracted.cs, verbatim, by line range, so that
// dotnet compiles upstream's own text against the stubs in golden/upstream/Stubs.cs.
//
//   node golden/extract.ts          (then: dotnet run --project golden/upstream -- vectors)
//
// Every range names the line it must start with: if upstream moves, extraction stops instead of copying the
// wrong lines. Paths are relative to the fork root (C:\workspace\AltspaceGames\blackjack), upstream commit 83f05db.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const fork = resolve(here, "..", "..", "..");

interface Range {
  file: string;
  cls: string;
  from: number;
  to: number;
  starts: string;
}

const RANGES: Range[] = [
  { file: "Scripts/DeckManager.cs", cls: "DeckManager", from: 53, to: 87, starts: "public void AddDeck()" },
  { file: "Scripts/PlayerDeck.cs", cls: "PlayerDeck", from: 150, to: 261, starts: "private void AddCardValue(int value)" },
  { file: "Scripts/Dealer.cs", cls: "Dealer", from: 61, to: 94, starts: "public void DealerPlay()" },
  { file: "Scripts/Dealer.cs", cls: "Dealer", from: 196, to: 295, starts: "private void AddCardValue(int value)" },
  { file: "Scripts/Player.cs", cls: "Player", from: 353, to: 378, starts: "public void Split()" },
  { file: "Scripts/Player.cs", cls: "Player", from: 403, to: 428, starts: "public void Bust()" },
  { file: "Scripts/Player.cs", cls: "Player", from: 468, to: 576, starts: "public void SetWinState()" },
  { file: "Scripts/Player.cs", cls: "Player", from: 599, to: 602, starts: "public void DelayedResetBet()" },
  { file: "Scripts/ChipController.cs", cls: "ChipController", from: 38, to: 110, starts: "public void AddChips(int value)" },
  // The deal schedule inside Controller.StartMatch, wrapped in a method of its own (Harness calls Schedule()).
  { file: "Scripts/Controller.cs", cls: "Controller", from: 204, to: 215, starts: "for (int i = 0; i < ActivePlayers.Length; i++)" },
];

const byClass = new Map<string, string[]>();
for (const r of RANGES) {
  const lines = readFileSync(join(fork, r.file), "utf8").replace(/^\uFEFF/, "").split(/\r?\n/);
  const first = (lines[r.from - 1] ?? "").trim();
  if (!first.startsWith(r.starts)) throw new Error(`${r.file}:${r.from} is "${first}", expected it to start with "${r.starts}"`);
  let text = lines.slice(r.from - 1, r.to).join("\n");
  if (r.cls === "Controller") text = "        public void Schedule()\n        {\n" + text + "\n        }";
  const list = byClass.get(r.cls) ?? [];
  list.push(`        // ---- ${r.file}:${r.from}-${r.to} (verbatim) ----\n${text}`);
  byClass.set(r.cls, list);
}

let out = "// Generated by golden/extract.ts from the upstream sources at commit 83f05db. Do not edit.\n";
out += "// Copyright 2022 CentauriCore, Apache License 2.0 (see the fork's LICENSE).\n\n";
out += "using System;\nusing UnityEngine;\nusing VRC.SDKBase;\nusing VRC.Udon.Common.Interfaces;\n\nnamespace CentauriCore.Blackjack\n{\n";
for (const [cls, parts] of byClass) out += `    public partial class ${cls}\n    {\n${parts.join("\n\n")}\n    }\n\n`;
out += "}\n";
writeFileSync(join(here, "upstream", "Extracted.cs"), out);
console.log(`extracted ${RANGES.length} ranges into golden/upstream/Extracted.cs`);
